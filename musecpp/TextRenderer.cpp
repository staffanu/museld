using namespace musevk;

TextRenderer::TextRenderer(std::string const &executable_dir, VulkanManager &vulkan_manager, std::shared_ptr<VulkanImage> const &image)
: m_vulkan_manager(vulkan_manager),
  m_image(image) {
    int bitmap_width = c_glyph_width * (int)c_monogram_font_definition.size();
    std::vector<uint8_t> data(bitmap_width * c_glyph_height);
    int index = 0;
    for (auto glyph : c_monogram_font_definition) {
        for (int i = 0; i < c_glyph_height; i++) {
            for (int j = 0; j < c_glyph_width; j++) {
                data[i * bitmap_width + index * c_glyph_width + j] = glyph.second[i] & (1 << j) ? 0x00ffffff : 0xff000000;
            }
        }
        m_char_indices[glyph.first] = index++;
    }

    m_font_buffer = vulkan_manager.createDeviceBuffer(Size(bitmap_width, c_glyph_height), data);

    m_render_text_shader = std::shared_ptr<ComputeShader>(new ComputeShader(m_vulkan_manager.getDevice(),
            "render_text", {m_font_buffer, image}, sizeof(uint16_t) * 64,
            musevk::VulkanUtil::loadSpirv(executable_dir, "render_text.comp"), musevk::Size(0)));
}

void TextRenderer::drawText(int x, int y, std::string s, int scale, CommandBuffer &command_buffer) {
    int total_width = c_glyph_width * (int)c_monogram_font_definition.size();
    std::vector<uint16_t> push_constants = {
            (uint16_t )x,    // top_left_x
            (uint16_t)y,     // top_left_y
            (uint16_t)scale, // scale
            c_glyph_width,   // font_width
            c_glyph_height,  // font_height
            (uint16_t)total_width, // font_total_width
            (uint16_t)s.size() // n_characters
    };

    for (char i : s) {
        int glyph_index = m_char_indices[i];
        push_constants.push_back(glyph_index);
    }
    assert(push_constants.size() <= 64); // max push constant size that is guaranteed
    push_constants.resize(64);

    m_render_text_shader->updateWorkgroup(Size(c_glyph_width * s.length() * scale, c_glyph_height * scale));
    command_buffer.enqueueComputeShader(m_render_text_shader, push_constants);
}

